#!/usr/bin/env node
/**
 * Offline migration generator.
 *
 * `prisma migrate dev` downloads a native schema engine. In locked-down build environments
 * (no access to binaries.prisma.sh) this script produces the same SQL using Prisma's
 * WebAssembly schema engine, diffing two Prisma schema files. No database objects are read or changed.
 *
 * Usage (from apps/api):
 *   git show HEAD:apps/api/prisma/schema.prisma > /tmp/prev.prisma
 *   node --experimental-wasm-modules scripts/migration-diff.mjs <snake_case_name> --from /tmp/prev.prisma
 *
 * Omit --from only for the very first migration (diff from an empty database).
 * Writes prisma/migrations/<timestamp>_<name>/migration.sql. Review it, then apply with
 * `prisma migrate deploy` (or psql in environments without the native engine).
 * Hand-written SQL (triggers, constraints, functions) goes in its own migration folder.
 */
import fs from 'node:fs';
import path from 'node:path';
import { SchemaEngine } from '@prisma/schema-engine-wasm';
import { PrismaPg } from '@prisma/adapter-pg';
import { bindMigrationAwareSqlAdapterFactory } from '@prisma/driver-adapter-utils';

const args = process.argv.slice(2);
const name = args[0];
const fromIdx = args.indexOf('--from');
const fromPath = fromIdx >= 0 ? args[fromIdx + 1] : null;
if (!name || !/^[a-z0-9_]+$/.test(name)) {
  console.error('usage: migration-diff.mjs <snake_case_name> [--from <previous-schema.prisma>]');
  process.exit(1);
}
const schemaPath = 'prisma/schema.prisma';
const migrationsDir = 'prisma/migrations';
const content = fs.readFileSync(schemaPath, 'utf8');

const hasMigrations = fs.existsSync(migrationsDir) && fs.readdirSync(migrationsDir).some((d) => /^\d{14}_/.test(d));
if (hasMigrations && !fromPath) {
  console.error('Migrations already exist: pass --from <previous schema.prisma> to diff against it.');
  process.exit(1);
}

// The engine opens a connection on start-up (any reachable PostgreSQL works); a
// datamodel-to-datamodel diff reads and writes nothing in it.
const factory = new PrismaPg({ connectionString: process.env.DATABASE_URL ?? 'postgresql://evida:evida@localhost:5432/evida' });
const engine = await SchemaEngine.new({ datamodels: [[schemaPath, content]] }, () => {}, bindMigrationAwareSqlAdapterFactory(factory));

const from = fromPath
  ? { tag: 'schemaDatamodel', files: [{ path: fromPath, content: fs.readFileSync(fromPath, 'utf8') }] }
  : { tag: 'empty' };

const res = await engine.diff({
  from,
  to: { tag: 'schemaDatamodel', files: [{ path: schemaPath, content }] },
  script: true,
  exitCode: null,
  filters: { externalTables: [], externalEnums: [] },
});
const sql = (res.stdout ?? '').trim();
if (!sql || sql.startsWith('-- This is an empty migration')) {
  console.log('No schema changes.');
  process.exit(0);
}
const stamp = new Date().toISOString().replace(/\D/g, '').slice(0, 14);
const dir = path.join(migrationsDir, `${stamp}_${name}`);
fs.mkdirSync(dir, { recursive: true });
fs.writeFileSync(path.join(dir, 'migration.sql'), sql + '\n');
if (!fs.existsSync(path.join(migrationsDir, 'migration_lock.toml'))) {
  fs.writeFileSync(path.join(migrationsDir, 'migration_lock.toml'), '# Please do not edit this file manually\nprovider = "postgresql"\n');
}
console.log(`Wrote ${dir}/migration.sql`);
process.exit(0);
